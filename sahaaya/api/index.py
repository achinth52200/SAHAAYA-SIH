@app.post("/api/v1/checkins")
def submit_checkin(body: CheckInRequest) -> Dict[str, Any]:
    scores = body.scores or {}
    urgent = float(scores.get("safety", 50)) <= 15 or float(scores.get("urgent_help", 0)) == 1
    record = {
        "checkin_id": str(uuid.uuid4()),
        "victim_id": body.victim_id,
        "checkin_date": datetime.now(timezone.utc).isoformat(),
        "scores": scores,
        "message": body.message,
        "channel": "web",
        "label": "[PROTOTYPE DATA - NOT REAL VICTIM DATA]",
    }
    checkins.append(record)
    routed = ["counsellor", "district_officer"] if urgent else []
    return {"status": "recorded", "checkin": record, "human_review": bool(routed), "routed_roles": routed}


@app.post("/api/v1/support-requests")
def create_support_request(body: SupportRequestBody) -> Dict[str, Any]:
    routed = ["counsellor", "district_officer"] if body.request_type == "urgent_safety" else ["counsellor"]
    record = {
        "request_id": str(uuid.uuid4()),
        "victim_id": body.victim_id,
        "request_type": body.request_type or "counselling",
        "message": body.message,
        "routed_roles": routed,
        "status": "open",
        "created_at": datetime.now(timezone.utc).isoformat(),
    }
    support_requests.append(record)
    return record


@app.get("/api/v1/support-requests")
def list_support_requests(role: Optional[str] = None, since: Optional[str] = None) -> List[Dict[str, Any]]:
    if role:
        return [r for r in support_requests if role in r.get("routed_roles", [])]
    return support_requests
