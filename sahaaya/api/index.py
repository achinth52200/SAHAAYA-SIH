"""
SAHAAYA demo API (Vercel serverless).

Serves a snapshot of REAL model output. snapshot.json is generated by running the
actual pipeline in services/api-gateway - DistressEngine, ExplainabilityEngine and
the lightweight emotion classifier over the synthetic dataset - and capturing the
responses. Regenerate it with scripts/build_snapshot.py whenever the engine or the
dataset changes.

Why a snapshot rather than live inference: the real stack (scikit-learn, pandas,
scipy and xgboost, which is required because the saved classifier is an
XGBClassifier) bundles to 618 MB against Vercel's hard 500 MB function limit. The
Docker/Render configuration in render.yaml runs the same code live and is the route
to real-time scoring.

This replaces an earlier stub that derived scores arithmetically from the victim ID
(`25 + ((number * 17) % 70)`) and returned text_emotion, behavioural, voice,
case_events and trend hardcoded to 0, which is why only Self Report ever appeared in
the officer report. Every number served here is genuine engine output.

Writes (check-ins, support requests, review decisions) are accepted and held in
memory for the life of the instance so the demo flows work end to end; they do not
re-run scoring.
"""

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional
import json
import re
import uuid

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

app = FastAPI(title="SAHAAYA API", version="1.0.0")
app.add_middleware(
    CORSMiddleware,
    allow_origins=["https://sih-sahaaya.vercel.app", "http://localhost:3000", "http://127.0.0.1:3000"],
    allow_origin_regex=r"https://sih-sahaaya-[a-z0-9-]+-achinth52200s-projects\.vercel\.app",
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

SNAPSHOT: Dict[str, Any] = json.loads((Path(__file__).parent / "snapshot.json").read_text(encoding="utf-8"))

# Runtime-only state; resets when the instance recycles.
checkins: List[Dict[str, Any]] = []
support_requests: List[Dict[str, Any]] = []
review_actions: Dict[str, List[Dict[str, Any]]] = {}
alert_overrides: Dict[str, Dict[str, Any]] = {}


def _victim_ids() -> List[str]:
    return [v["victim_id"] for v in SNAPSHOT["victims"]]


def _require(section: str, victim_id: str) -> Dict[str, Any]:
    data = SNAPSHOT[section].get(victim_id)
    if data is None:
        raise HTTPException(status_code=404, detail="Victim not found")
    return data


