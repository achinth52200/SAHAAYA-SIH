# ===== Review workflow =====

def _alerts() -> List[Dict[str, Any]]:
    return [alert_overrides.get(a["alert_id"], a) for a in SNAPSHOT["alerts"]]


@app.get("/api/v1/review/alerts")
def review_alerts(
    status: Optional[str] = None,
    priority: Optional[str] = None,
    victim_id: Optional[str] = None,
    limit: int = 200,
) -> List[Dict[str, Any]]:
    result = _alerts()
    if status:
        result = [a for a in result if a.get("status") == status]
    if priority:
        result = [a for a in result if a.get("priority") == priority]
    if victim_id:
        result = [a for a in result if a.get("victim_id") == victim_id]
    return result[:limit]


@app.get("/api/v1/review/alerts/{alert_id}")
def review_alert(alert_id: str) -> Dict[str, Any]:
    for alert in _alerts():
        if alert["alert_id"] == alert_id:
            return alert
    raise HTTPException(status_code=404, detail="Alert not found")


@app.get("/api/v1/review/alerts/{alert_id}/history")
def alert_history(alert_id: str) -> List[Dict[str, Any]]:
    return review_actions.get(alert_id, [])


@app.get("/api/v1/review/alerts/{alert_id}/interventions")
@app.get("/api/v1/review/interventions")
def interventions(alert_id: Optional[str] = None, victim_id: Optional[str] = None) -> List[Dict[str, Any]]:
    return []


@app.post("/api/v1/review/alerts/{alert_id}/review")
def submit_review(alert_id: str, body: ReviewBody) -> Dict[str, Any]:
    alert = json.loads(json.dumps(review_alert(alert_id)))
    status_for = {
        "dismiss": "false_positive",
        "escalate": "escalated",
        "confirm_intervene": "intervention_decided",
        "confirm_monitor": "intervention_decided",
        "request_more_info": "in_review",
    }
    alert["status"] = status_for.get(body.decision, "in_review")
    alert["reviewed_by"] = body.actor_id
    alert["review_decision"] = body.decision
    alert["updated_at"] = datetime.now(timezone.utc).isoformat()
    alert_overrides[alert_id] = alert

    review_actions.setdefault(alert_id, []).append({
        "action_id": f"ACT_{uuid.uuid4().hex[:12].upper()}",
        "alert_id": alert_id,
        "actor_id": body.actor_id,
        "actor_role": body.actor_role,
        "action": body.decision,
        "notes": body.notes,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    })
    return alert


