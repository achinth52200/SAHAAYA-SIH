@app.get("/api/v1/dashboard/district/{district_id}")
def district(district_id: str) -> Dict[str, Any]:
    members = [v for v in SNAPSHOT["victims"] if v.get("district") == district_id]
    bands = {"Green": 0, "Yellow": 0, "Orange": 0, "Red": 0}
    for v in members:
        if v.get("latest_band") in bands:
            bands[v["latest_band"]] += 1
    return {
        "district": district_id,
        "total_victims": len(members),
        "band_distribution": bands,
        "high_risk_count": bands["Orange"] + bands["Red"],
        "victims": [{"victim_id": v["victim_id"], "case_type": v["case_type"],
                     "score": v.get("latest_score"), "band": v.get("latest_band"),
                     "trend": v.get("trend"),
                     "escalation_7d": v.get("escalation_probability_7d")} for v in members],
    }


@app.get("/api/v1/dashboard/state/{state_id}")
def state(state_id: str) -> Dict[str, Any]:
    members = [v for v in SNAPSHOT["victims"] if v.get("state") == state_id]
    bands = {"Green": 0, "Yellow": 0, "Orange": 0, "Red": 0}
    for v in members:
        if v.get("latest_band") in bands:
            bands[v["latest_band"]] += 1
    districts: Dict[str, Dict[str, Any]] = {}
    for v in members:
        d = districts.setdefault(v["district"], {
            "district": v["district"], "total_victims": 0,
            "band_distribution": {"Green": 0, "Yellow": 0, "Orange": 0, "Red": 0},
            "high_risk_count": 0})
        d["total_victims"] += 1
        if v.get("latest_band") in d["band_distribution"]:
            d["band_distribution"][v["latest_band"]] += 1
        d["high_risk_count"] = d["band_distribution"]["Orange"] + d["band_distribution"]["Red"]
    high = bands["Orange"] + bands["Red"]
    return {
        "state": state_id,
        "total_victims": len(members),
        "total_districts": len(districts),
        "band_distribution": bands,
        "high_risk_count": high,
        "high_risk_percentage": round(high / len(members) * 100) if members else 0,
        "districts": list(districts.values()),
    }


